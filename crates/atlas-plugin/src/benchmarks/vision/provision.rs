//! `~/.atlas/artifacts/vision` — the fixture images, laid down on `load()`.
//!
//! Follows the BFCL provisioning pattern (`benchmarks/bfcl/provision.rs`):
//! assets are compiled into the binary from `crates/atlas-plugin/assets/`,
//! written out only when their bytes differ, and gated behind a [`Stamp`] so a
//! run that has already provisioned does no I/O.
//!
//! Why provision at all for 132 KB of PNGs, when `include_bytes!` alone would
//! do: a benchmark runs from an installed binary on a box that need not have
//! the repo, and a materialised directory is what makes a failing run
//! reproducible by hand — the operator can point any HTTP client at the exact
//! bytes the run used.
//!
//! ## Relationship to `tests/fixtures/images/`
//!
//! These are the SAME eight images, generated by `scripts/gen_test_images.py`,
//! which is their source of truth. They are copied here rather than referenced
//! because nothing in this repo reaches outside its own crate for an asset —
//! BFCL's `include_str!("../../../assets/bfcl/…")` escapes `src/` but stays in
//! the crate, and `cargo` would not package a path climbing to `tests/`.
//!
//! ★ Regenerate BOTH locations together. `scripts/gen_test_images.py` is fully
//! deterministic (no RNG), so a drift between the two copies means one was
//! regenerated and the other was not. `assets_match_the_repo_fixtures` in
//! `provision_tests.rs` fails on exactly that, whenever the repo is present.

