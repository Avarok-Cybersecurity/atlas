// Builders for the messages that drive another machine.
//
// Pure and plain `.js` for the house reason: these shapes must be testable,
// and a file holding runes cannot be imported by the test runner. The client
// wrapper becomes transport-only; every frame a control action puts on the
// wire is built — and therefore tested — here.
//
// Each builder returns the exact serde representation of the protocol-4
// `ClientMsg` variant: internally tagged on `type`, snake_case, fields in
// declaration order, `on: null` written out rather than omitted. Byte-exact
// on purpose — the fixtures in the test file were generated by serde_json
// against the Rust enum, so a drift between this file and the crate fails a
// test instead of failing a launch.
//
// Every builder throws on input it cannot vouch for rather than building a
// best-guess frame. A malformed frame is refused by the agent anyway; failing
// here names the caller's bug instead of surfacing as a wire error attributed
// to the wrong machine.

import { nodeId } from './ingest.js';

/** Correlation ids and line counts ride a u32 on the wire. */
const U32_MAX = 0xffffffff;

/**
 * A correlation id the wire can carry.
 *
 * @param {unknown} id
 * @returns {number}
 */
function correlation(id) {
  if (!Number.isInteger(id) || id < 0 || id > U32_MAX) {
    throw new TypeError(`a correlation id is a u32, got ${String(id)}`);
  }
  return id;
}

/**
 * The `on` target: null for this machine, otherwise a node id.
 *
 * Required, never defaulted. "Local" and "forgot to say" must not look the
 * same at a call site — a Stop that silently went local because a caller
 * dropped an argument would stop the wrong machine's launch.
 *
 * @param {unknown} on
 * @returns {string|null}
 */
function target(on) {
  if (on === null) return null;
  const id = nodeId(on);
  if (id === null) {
    throw new TypeError('`on` must be null (this machine) or a 64-hex node id');
  }
  return id;
}

/**
 * A recipe id plausible enough to put on the wire.
 *
 * Not a re-implementation of the Rust parser — recipe ids come FROM the agent
 * (`RecipeInfo.id`), so a valid one is already in hand. This refuses the
 * shapes that mean a caller bug: not a string, empty, oversized, or carrying
 * characters `RecipeId`'s alphabet can never hold.
 *
 * @param {unknown} recipe
 * @returns {string}
 */
function recipeId(recipe) {
  if (typeof recipe !== 'string' || !/^[a-z0-9.-]{1,64}$/.test(recipe)) {
    throw new TypeError(`not a recipe id: ${String(recipe)}`);
  }
  return recipe;
}

/**
 * Settings as the wire carries them: a plain object of bool | finite number |
 * string values, keys sorted to match `BTreeMap` order.
 *
 * `undefined` and `NaN` are refused rather than dropped: JSON.stringify turns
 * one into a missing key and the other into `null`, and a setting that
 * silently vanished from a launch is exactly the failure the `unapplied`
 * machinery exists to surface.
 *
 * @param {unknown} settings
 * @returns {object}
 */
function settingsMap(settings) {
  if (settings === null || typeof settings !== 'object' || Array.isArray(settings)) {
    throw new TypeError('settings must be a plain object');
  }
  const out = {};
  for (const key of Object.keys(settings).sort()) {
    const v = settings[key];
    const ok =
      typeof v === 'boolean' || typeof v === 'string' || (typeof v === 'number' && Number.isFinite(v));
    if (!ok) throw new TypeError(`setting ${key} is not a boolean, finite number, or string`);
    out[key] = v;
  }
  return out;
}

/**
 * `allow_control` must be said, not implied.
 *
 * Required for the same reason the protocol defaults it to false: consent to
 * remote stop is a decision, and a builder that defaulted it would let a
 * refactor grant it by accident. Mirrors `readDecision`'s required
 * `expectTrusted`.
 *
 * @param {unknown} v
 * @returns {boolean}
 */
function consent(v) {
  if (v !== true && v !== false) {
    throw new TypeError('allow_control must be explicitly true or false');
  }
  return v;
}

/** Ask a node for its recipe inventory. */
export function listRecipes(id, on) {
  return { type: 'list_recipes', id: correlation(id), on: target(on) };
}

/** Render the command a launch would run, without running it. */
export function preview(id, recipe, settings, on) {
  return {
    type: 'preview',
    id: correlation(id),
    recipe: recipeId(recipe),
    settings: settingsMap(settings),
    on: target(on)
  };
}

/** Start a recipe. */
export function launch(id, recipe, settings, on) {
  return {
    type: 'launch',
    id: correlation(id),
    recipe: recipeId(recipe),
    settings: settingsMap(settings),
    on: target(on)
  };
}

/** Stop a running launch. */
export function stop(id, recipe, on) {
  return { type: 'stop', id: correlation(id), recipe: recipeId(recipe), on: target(on) };
}

/** Ask what is running. */
export function status(id, on) {
  return { type: 'status', id: correlation(id), on: target(on) };
}

/** Ask how a running launch is doing. */
export function launchStats(id, recipe, on) {
  return { type: 'launch_stats', id: correlation(id), recipe: recipeId(recipe), on: target(on) };
}

/** Read the tail of a launch's log. The agent caps `lines` again on its side. */
export function launchLogs(id, recipe, lines, on) {
  if (!Number.isInteger(lines) || lines < 1 || lines > U32_MAX) {
    throw new TypeError(`lines must be a positive u32, got ${String(lines)}`);
  }
  return {
    type: 'launch_logs',
    id: correlation(id),
    recipe: recipeId(recipe),
    lines,
    on: target(on)
  };
}

/** Open a join window, saying out loud whether the joiner may control this machine. */
export function mintJoinCode(id, allowControl) {
  return { type: 'mint_join_code', id: correlation(id), allow_control: consent(allowControl) };
}

/** Trust a peer whose words matched, saying out loud whether it may control this machine. */
export function confirmPairing(id, node, allowControl) {
  const n = nodeId(node);
  if (n === null) throw new TypeError('confirm_pairing needs the node id being trusted');
  return { type: 'confirm_pairing', id: correlation(id), node: n, allow_control: consent(allowControl) };
}
