//! What the run leaves behind: a paste-ready MODEL.toml block and the
//! evidence behind it.
//!
//! The TOML block is the product — it is what `--expert-category` reads
//! after a rebuild. The stats JSON is why anyone should believe it: full
//! per-expert mass, plus the cross-category overlap that says whether the
//! categories discriminate at all.

use std::collections::BTreeMap;

use super::aggregate::{Accumulator, CategoryBudget, mean_jaccard};

/// Render the `[expert_categories]` block.
///
/// Self-describing on purpose: found in a MODEL.toml a year from now, the
/// header has to say what measured it, at what coverage, over how many
/// prompts, and that editing this file invalidates the target's gate
/// closure hash.
pub fn toml_block(
    model: &str,
    corpus_sha256: &str,
    max_tokens: usize,
    budgets: &[CategoryBudget],
) -> String {
    let mut out = String::new();
    out.push_str(
        "# ── Generated by the `expert-categories` benchmark ────────────────\n\
         # Maps a prompt category to the experts it actually routes to, per\n\
         # MoE layer. `spark serve --expert-category <name>` loads only these.\n",
    );
    out.push_str(&format!("# model      = \"{model}\"\n"));
    out.push_str(&format!("# corpus     = sha256 {corpus_sha256}\n"));
    out.push_str(&format!(
        "# generation = max_tokens {max_tokens}, temperature 0, seed 0\n"
    ));
    out.push_str(
        "#\n\
         # Paste into kernels/<hw>/<model>/MODEL.toml and REBUILD: this table is\n\
         # read at build time, like [dflash]. Editing MODEL.toml also invalidates\n\
         # that target's gate closure hash, which is deliberate — the binary's\n\
         # expert set changed, so prior records no longer describe it.\n\n",
    );
    for b in budgets {
        out.push_str(&format!("[expert_categories.{}]\n", b.category));
        out.push_str(&format!("coverage = {:.2}\n", b.coverage));
        out.push_str(&format!("prompts = {}\n", b.totals.prompts));
        out.push_str(&format!("tokens_routed = {}\n", b.totals.tokens_routed));
        for (layer, ids) in &b.layers {
            let list = ids
                .iter()
                .map(|i| i.to_string())
                .collect::<Vec<_>>()
                .join(", ");
            out.push_str(&format!("layers.\"{layer}\" = [{list}]\n"));
        }
        out.push('\n');
    }
    out
}

/// The evidence artifact: every expert's mass per category and layer, plus
/// the pairwise overlap of the budgeted sets.
pub fn stats_json(
    model: &str,
    corpus_sha256: &str,
    coverage: f64,
    acc: &Accumulator,
    budgets: &[CategoryBudget],
    eas: Option<&super::eas::Eas>,
) -> serde_json::Value {
    let mut categories = serde_json::Map::new();
    for b in budgets {
        let layers: serde_json::Map<String, serde_json::Value> = acc
            .layer_mass(&b.category)
            .into_iter()
            .map(|(layer, experts)| {
                let total: f64 = experts.iter().map(|(_, _, m)| *m).sum();
                (
                    layer.to_string(),
                    serde_json::json!({
                        "total_mass": total,
                        // [id, count, mass] triples — the full distribution,
                        // not just what survived the budget, so a different
                        // coverage can be evaluated without re-measuring.
                        "experts": experts
                            .iter()
                            .map(|(e, c, m)| serde_json::json!([e, c, m]))
                            .collect::<Vec<_>>(),
                        "budgeted": b
                            .layers
                            .iter()
                            .find(|(l, _)| *l == layer)
                            .map(|(_, ids)| ids.clone())
                            .unwrap_or_default(),
                    }),
                )
            })
            .collect();
        categories.insert(
            b.category.clone(),
            serde_json::json!({
                "prompts": b.totals.prompts,
                "tokens_routed": b.totals.tokens_routed,
                "unattributed_rows": b.totals.unattributed_rows,
                "mean_experts_per_layer": mean_experts(b),
                "layers": layers,
            }),
        );
    }

    let mut overlap = serde_json::Map::new();
    for (i, a) in budgets.iter().enumerate() {
        for b in budgets.iter().skip(i + 1) {
            overlap.insert(
                format!("{}|{}", a.category, b.category),
                serde_json::json!(mean_jaccard(a, b)),
            );
        }
    }

    // EAS travels with everything needed to reproduce and judge it. A score
    // quoted without its corpus, its null and its category count is not
    // comparable to anything — the same discipline a BFCL number needs its
    // draw fingerprint for.
    let eas_block = eas.map(|e| {
        serde_json::json!({
            "version": "EAS-1.0",
            "eas": e.eas,
            "eas_count": e.eas_count,
            "per_category": e
                .category_names
                .iter()
                .zip(e.per_category.iter())
                .map(|(n, v)| serde_json::json!({"category": n, "eas": v}))
                .collect::<Vec<_>>(),
            "per_layer": e
                .per_layer
                .iter()
                .map(|(l, v)| serde_json::json!({"layer": l, "eas": v}))
                .collect::<Vec<_>>(),
            "category_entropy_nats": e.category_entropy,
            "null": {
                "permutations": e.permutations,
                "mean_mi_nats": e.null_mean_mi,
                "sd_mi_nats": e.null_sd_mi,
                "layers_at_chance": e.layers_at_chance,
            },
            "prompts": e.prompts,
            "categories": e.category_names.len(),
            "dead_experts": e.dead_experts,
            // Stated, not implied: the score is defined against THIS corpus.
            // Category overlap caps what any model can reach on it, so a
            // number from another taxonomy is a different measurement.
            "comparable_across": "models measured on this corpus_sha256; NOT across corpora",
        })
    });

    serde_json::json!({
        "model": model,
        "corpus_sha256": corpus_sha256,
        "coverage": coverage,
        "eas": eas_block,
        "top_k": acc.top_k(),
        "num_experts": acc.num_experts(),
        "categories": categories,
        // Mean Jaccard of the budgeted sets over shared layers. Low between
        // different categories is the whole premise: it is what makes a
        // per-category expert set smaller than the union.
        "jaccard_budgeted": overlap,
    })
}

/// Mean budgeted experts per layer — the memory story in one number.
pub fn mean_experts(b: &CategoryBudget) -> f64 {
    if b.layers.is_empty() {
        return 0.0;
    }
    b.layers
        .iter()
        .map(|(_, ids)| ids.len() as f64)
        .sum::<f64>()
        / b.layers.len() as f64
}

/// Pairwise overlaps, most-similar first — the summary a reader scans to
/// see whether two categories are worth separating.
pub fn overlap_pairs(budgets: &[CategoryBudget]) -> Vec<(String, String, f64)> {
    let mut pairs: Vec<(String, String, f64)> = Vec::new();
    for (i, a) in budgets.iter().enumerate() {
        for b in budgets.iter().skip(i + 1) {
            pairs.push((a.category.clone(), b.category.clone(), mean_jaccard(a, b)));
        }
    }
    pairs.sort_by(|x, y| y.2.partial_cmp(&x.2).unwrap_or(std::cmp::Ordering::Equal));
    pairs
}

/// SHA-256 of the corpus bytes, so a report names the exact rows it came
/// from and two reports can be compared without trusting their labels.
pub fn corpus_sha256(corpus: &str) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(corpus.as_bytes());
    format!("{:x}", h.finalize())
}

/// Per-category totals for the run table.
pub fn category_rows(budgets: &[CategoryBudget]) -> BTreeMap<String, (u64, f64)> {
    budgets
        .iter()
        .map(|b| (b.category.clone(), (b.totals.prompts, mean_experts(b))))
        .collect()
}

