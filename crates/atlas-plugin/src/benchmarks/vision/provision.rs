/// Bump when the fixture SET changes — a new image, a regenerated one, a
/// different size. The stamp is content-derived rather than a hand-maintained
/// version so a regenerated PNG re-provisions by itself.
fn stamp_value() -> String {
    let mut acc: u64 = 1469598103934665603; // FNV-1a offset basis
    for (name, bytes, _, _) in FIXTURES {
        for b in name.as_bytes().iter().chain(bytes.iter()) {
            acc ^= *b as u64;
            acc = acc.wrapping_mul(1099511628211);
        }
    }
    format!("vision-fixtures-v1-{acc:016x}")
}

/// `~/.atlas/artifacts/vision`, matching BFCL's `~/.atlas/artifacts/bfcl`.
pub const PLUGIN_ID: &str = "vision";

/// Materialise the fixtures. Idempotent; cheap when already current.
pub fn provision(store: &ArtifactStore) -> Result<std::path::PathBuf> {
    let dir = store.plugin_dir(PLUGIN_ID)?;
    let stamp = Stamp::new(&dir, ".provisioned", stamp_value());
    if stamp.is_current() {
        return Ok(dir);
    }
    for (name, bytes, _, _) in FIXTURES {
        write_asset_bytes(&dir, name, bytes)?;
    }
    // LAST — a stamp written before the writes complete turns a partial
    // directory into a permanent "already done".
    stamp.commit()?;
    Ok(dir)
}

