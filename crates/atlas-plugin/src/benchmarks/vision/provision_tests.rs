//! Host-side. No GPU, no endpoint.

use super::*;
use crate::artifacts::ArtifactStore;

fn tmp(name: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("atlas-vision-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn is_png(b: &[u8]) -> bool {
    b.starts_with(&[0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a])
}

fn is_jpeg(b: &[u8]) -> bool {
    b.starts_with(&[0xff, 0xd8, 0xff])
}

/// Magic bytes must agree with the extension. The ladder is no longer
/// PNG-only: the decode-variant rungs deliberately include a JPEG, because a
/// suite that only ever sends 8-bit RGB PNGs cannot notice a decoder that
/// mishandles anything else. What must still hold is that each file IS what
/// it claims — the server dispatches on content, so a mislabelled fixture
/// would quietly test a different path than the one named.
#[test]
fn every_baked_fixture_matches_its_declared_format() {
    for (name, bytes, _, _) in FIXTURES {
        if name.ends_with(".jpg") || name.ends_with(".jpeg") {
            assert!(is_jpeg(bytes), "{name} is not a JPEG");
        } else {
            assert!(is_png(bytes), "{name} is not a PNG");
        }
        // The 8x8 rung is genuinely tiny — a valid PNG of it is ~120 bytes —
        // so the truncation floor has to be below that or the smallest
        // fixture in the ladder reads as damaged.
        assert!(bytes.len() > 100, "{name} looks truncated");
    }
    for (name, bytes) in EXIF_PAIR {
        assert!(is_jpeg(bytes), "{name} is not a JPEG");
        assert!(bytes.len() > 100, "{name} looks truncated");
    }
}

#[test]
fn provision_writes_every_fixture_then_stamps() {
    let root = tmp("provision");
    let store = ArtifactStore::with_root(&root);
    let dir = provision(&store).expect("provision");
    for (name, bytes) in FIXTURES
        .iter()
        .map(|(name, bytes, _, _)| (*name, *bytes))
        .chain(EXIF_PAIR.iter().copied())
    {
        let got = std::fs::read(dir.join(name)).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(&got, bytes, "{name} was written with different bytes");
    }
    assert_eq!(
        std::fs::read_to_string(dir.join(".provisioned")).expect("read vision stamp"),
        stamp_value()
    );
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn a_second_provision_is_a_no_op() {
    // The stamp exists so a repeat run does no I/O; if it rewrote the files
    // every load() would churn mtimes that downstream stamps depend on.
    let root = tmp("idempotent");
    let store = ArtifactStore::with_root(&root);
    let dir = provision(&store).expect("first");
    let victim = dir.join(EXIF_PAIR[0].0);
    let original_permissions = std::fs::metadata(&victim).unwrap().permissions();
    let mut readonly_permissions = original_permissions.clone();
    readonly_permissions.set_readonly(true);
    std::fs::set_permissions(&victim, readonly_permissions).unwrap();
    provision(&store).expect("current stamp must return before EXIF writes");
    std::fs::set_permissions(&victim, original_permissions).unwrap();
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn a_stale_stamp_forces_reprovision() {
    // Non-vacuity for the test above: prove the skip is the STAMP's doing and
    // not simply that provisioning never writes.
    let root = tmp("stale");
    let store = ArtifactStore::with_root(&root);
    let dir = provision(&store).expect("first");
    let victim = dir.join(EXIF_PAIR[1].0);
    std::fs::write(&victim, b"corrupted").unwrap();
    std::fs::write(dir.join(".provisioned"), "not-the-current-stamp").unwrap();
    provision(&store).expect("reprovision");
    assert_eq!(
        std::fs::read(&victim).unwrap(),
        EXIF_PAIR[1].1,
        "a stale stamp did not force the EXIF fixture to be rewritten"
    );
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn the_stamp_tracks_fixture_content() {
    // Content-derived, so a regenerated PNG re-provisions without anyone
    // remembering to bump a version literal.
    let v = stamp_value();
    assert_eq!(v, "vision-fixtures-v1-67ae2560abe3e0cc");
    assert_eq!(v, stamp_value(), "stamp is not deterministic");
    assert_ne!(
        crate::benchmarks::content_stamp("vision-fixtures-v1", [("image", b"one".as_slice())]),
        crate::benchmarks::content_stamp("vision-fixtures-v1", [("image", b"two".as_slice())])
    );
}

#[test]
fn assets_match_the_repo_fixtures() {
    // The baked copies come from tests/fixtures/images/, generated by
    // scripts/gen_test_images.py. That script is deterministic, so a
    // difference means one copy was regenerated and the other was not.
    // Skipped when the repo is not present (installed binary, packaged crate).
    let repo = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/images");
    if !repo.is_dir() {
        return;
    }
    for (name, bytes) in FIXTURES
        .iter()
        .map(|(name, bytes, _, _)| (*name, *bytes))
        .chain(EXIF_PAIR.iter().copied())
    {
        let path = repo.join(name);
        let Ok(on_disk) = std::fs::read(&path) else {
            panic!("{name} is baked in but missing from {}", repo.display());
        };
        assert_eq!(
            &on_disk, bytes,
            "{name} has DRIFTED from tests/fixtures/images — regenerate both \
             with scripts/gen_test_images.py"
        );
    }
}

#[test]
fn a_failed_exif_write_does_not_commit_the_stamp() {
    let root = tmp("partial-exif");
    let store = ArtifactStore::with_root(&root);
    let dir = store
        .plugin_dir(PLUGIN_ID)
        .expect("vision artifact directory");
    std::fs::create_dir(dir.join(EXIF_PAIR[0].0)).expect("block the first EXIF path");
    assert!(
        provision(&store).is_err(),
        "the obstructed EXIF write must fail"
    );
    assert!(
        !dir.join(".provisioned").exists(),
        "the complete main ladder with a missing EXIF fixture is still partial"
    );
    std::fs::remove_dir_all(root).expect("remove temporary vision root");
}
